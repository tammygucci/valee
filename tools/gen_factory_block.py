"""(Vallée) Move the factory sample sets out of the firmware, into the FM-1's sample area.

Reads build/gen/felucca_samples.h as tools/gen_samples.py wrote it and rewrites it without SMP_DATA (the zone
table, the sets and the presets stay in the firmware), with SMP_FACT_LEN and SMP_FACT_CRC. Writes:

  build/gen/felucca_samples_blob.h  the block as a C array (SMP_FACT_BLOB): the emulator, the host tests
  build/vallee-samples.bin          the block for the unit: the installer writes it at flash 0xA0000

The block: a 512-byte header (u32 magic "VSMP", u16 version 1, u16 0, u32 data length, u32 CRC-32 of the data,
then 0xFF) and the data (IMA ADPCM, the zones' offsets count from it). eng_sample.c checks magic, version,
length and CRC against this build's at boot: a block that is missing, partly written or from another build
plays no sample (the sine of a missing sample), never noise.
"""
import re
import struct
import sys
import zlib
from pathlib import Path

MAGIC = 0x504D5356          # "VSMP"
HDR = 512


def main(header, blob_h, blob_bin):
    src = Path(header).read_text()
    m = re.search(r"static const uint8_t SMP_DATA\[(\d+)\] = \{(.*?)\};\n", src, re.S)
    if not m:
        if "SMP_FACT_LEN" in src:
            return                                  # already moved (an unchanged cached header)
        raise SystemExit("gen_factory_block: no SMP_DATA in " + header)
    n = int(m.group(1))
    data = bytes(int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(2)))
    if len(data) != n:
        raise SystemExit(f"gen_factory_block: SMP_DATA {len(data)} bytes, declared {n}")
    crc = zlib.crc32(data) & 0xFFFFFFFF
    head = struct.pack("<IHHII", MAGIC, 1, 0, n, crc)
    block = head + b"\xff" * (HDR - len(head)) + data
    if len(block) > 0x3C000:
        raise SystemExit(f"gen_factory_block: {len(block)} bytes, the sample area holds {0x3C000}")
    out = src[:m.start()] + (f"#define SMP_FACT_LEN {n}u\n#define SMP_FACT_CRC 0x{crc:08X}u\n"
                             f"#define SMP_FACT_HDR {HDR}u\n") + src[m.end():]
    Path(header).write_text(out)
    rows = ",\n".join(", ".join(str(b) for b in block[i:i + 32]) for i in range(0, len(block), 32))
    Path(blob_h).write_text("/* generated by tools/gen_factory_block.py: the factory sample block (emulator, tests) */\n"
                            f"static const uint8_t SMP_FACT_BLOB[{len(block)}] __attribute__((aligned(4))) = {{\n"
                            f"{rows}\n}};\n")
    Path(blob_bin).write_bytes(block)
    print(f"factory samples: {n} B data, block {len(block)} B, crc {crc:08x}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
