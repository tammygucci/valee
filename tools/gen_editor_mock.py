"""(Vallée, the SPAMPY sound) The web editor's mock device (web/editor.html) from the firmware's tables.

    python3 tools/gen_editor_mock.py build/host/desc.json web/editor.html

desc.json is tests/descdump.c's (run_tests.sh writes it). Rewrites, between their markers, the mock's engines (ENG:
titles, EDIT, presets), the ENGINE selector's names, the display order (ENGINE_ORDER), the power-on sounds and the FM6
patches (init, factory), so the mock always matches what the firmware has (web/test_web.mjs checks it).
"""
import json
import re
import sys
from pathlib import Path


def js(v):
    return json.dumps(v, separators=(", ", ": ")).replace('"label"', "label").replace('"fmt"', "fmt") \
        .replace('"min"', "min").replace('"max"', "max").replace('"def"', "def").replace('"names"', "names") \
        .replace('"unit"', "unit")


def block(src, start, end, new, what):
    a = src.find(start)
    if a < 0:
        raise SystemExit(f"gen_editor_mock: {what}: start not found")
    b = src.find(end, a)
    if b < 0:
        raise SystemExit(f"gen_editor_mock: {what}: end not found")
    return src[:a] + new + src[b + len(end):]


def main(desc, html):
    d = json.loads(Path(desc).read_text())
    s = Path(html).read_text()
    # engines
    rows = []
    for e in d["ENG"]:
        edit = ", ".join(js(x) for x in e["edit"])
        pres = ",\n      ".join(
            f'{{ name: {json.dumps(p["name"])}, e: {js(p["e"])}, env: {js(p["env"])}, mono: {p["mono"]}, pat: 0, '
            f'more: {js(p["more"])} }}' for p in e["presets"])
        rows.append(f'    {{ name: {json.dumps(e["name"])}, titles: {js(e["titles"])}, edit: [{edit}],\n'
                    f'      presets: [{pres}] }}')
    eng = ("  /* ((Vallée, the SPAMPY sound) generated by tools/gen_editor_mock.py from the firmware's tables */\n"
           "  const ENG = [\n" + ",\n".join(rows) + "\n  ];\n")
    s = block(s, "  const ENG = [\n", "\n  ];\n", eng, "ENG")
    # the ENGINE selector (G_ENGSEL) names
    names = ", ".join(json.dumps(n) for n in d["GP"][d["G_ENGSEL"]]["names"])
    s = re.sub(r'E\("ENGINE", \[[^\]]*\], 0\)', f'E("ENGINE", [{names}], 0)', s, count=1)
    # the display order
    order = ", ".join(json.dumps(n) for n in d["ORDER"])
    s = block(s, "const ENGINE_ORDER = [", "];", f"const ENGINE_ORDER = [{order}];", "ENGINE_ORDER")
    # the power-on sounds: tracks 2..6, then 1 (the mock's order: track 1 selected last)
    td = d["TRK_DEF"]
    seq = [[i, td[i][0], td[i][1]] for i in range(1, len(td))] + [[0, td[0][0], td[0][1]]]
    s = re.sub(r"  \[\[1, [^\n]*\]\]\.forEach\(\(\[i, e, p\]\) => \{ st\.sel = i; setEngine\(e\); applyPreset\(p\); \}\);",
               f"  {js(seq)}.forEach(([i, e, p]) => {{ st.sel = i; setEngine(e); applyPreset(p); }});", s, count=1)
    # FM6 patches
    f6 = d["FM6"]
    s = block(s, "  const INIT_PK = [", "];", "  const INIT_PK = [" + ",".join(str(x) for x in f6["init"]) + "];", "INIT_PK")
    fac = ",\n".join("    [" + ",".join(str(x) for x in p) + "]" for p in f6["factory"])
    s = block(s, "  const FACTORY_PK = [\n", "\n  ];", "  const FACTORY_PK = [\n" + fac + "\n  ];", "FACTORY_PK")
    Path(html).write_text(s)
    print(f"gen_editor_mock: {len(d['ENG'])} engines, {sum(len(e['presets']) for e in d['ENG'])} sounds")


if __name__ == "__main__":
    main(*sys.argv[1:3])
