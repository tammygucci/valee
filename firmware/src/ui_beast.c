static const uint8_t XB_EON = 15u;   /* the families whose eyes land on the body alone (bit k) */

/* a half row (3 bytes) onto row y, mirrored; on: only where the body is */
static void xb_put(uint8_t px[12][12], int32_t y, const uint8_t *b, int on)
{
    uint32_t v = (uint32_t)b[0] << 16 | (uint32_t)b[1] << 8 | b[2], i, c;
    if (y < 0 || y > 11)
        return;
    for (i = 0; i < 6u; i++)
        if ((c = (v >> (15u - 3u * i)) & 7u) != 0u && (!on || px[y][i])) {
            px[y][i] = (uint8_t)c;
            px[y][11u - i] = (uint8_t)c;
        }
}
/* the creature of track k's family for sound n */
static void xe_beast_px(uint32_t k, uint32_t n, uint8_t px[12][12])
{
    uint32_t c = n % 256u, j, p;
    k %= NTRK;
    memset(px, 0, 144);
    for (j = 0; j < 12u; j++)
        xb_put(px, (int32_t)j, XB_B[k][c % 4u][j], 0);
    for (p = 0; p < 3u; p++) {                      /* the eyes, what is round it, its mark */
        const uint8_t *o = XB_O[k][p][(c >> (2u + 2u * p)) % 4u];
        for (j = 0; j < 3u; j++)
            xb_put(px, (int32_t)o[0] + (int32_t)j, o + 1 + 3u * j, p == 0u && ((XB_EON >> k) & 1u));
    }
}
/* packed as a sprite (ui_sprite): w, h, 3 bits a pixel, a spare byte */
#define XB_ART_N (3u + (12u * 12u * 3u + 7u) / 8u + 1u)
static void xb_pack(const uint8_t px[12][12], uint8_t *out)   /* (as gen_sprites.py packs: 3 bits a cell) */
{
    uint32_t acc = 0, nb = 0, o = 3, j, i;
    out[0] = 12;
    out[1] = 12;
    out[2] = 3;
    for (j = 0; j < 12u; j++)
        for (i = 0; i < 12u; i++) {
            acc = acc << 3 | px[j][i];
            nb += 3u;
            if (nb >= 8u) {
                out[o++] = (uint8_t)(acc >> (nb - 8u));
                nb -= 8u;
            }
        }
    if (nb)
        out[o++] = (uint8_t)(acc << (8u - nb));
    out[o] = 0;
}
static void xe_beast_art(uint32_t k, uint32_t n, uint8_t *out)
{
    uint8_t px[12][12];
    xe_beast_px(k, n, px);
    xb_pack(px, out);
}
/* a name's number for a sound that is not a factory one */
static uint32_t xb_hash(const char *s)
{
    uint32_t h = 2166136261u;
    while (*s)
        h = (h ^ (uint8_t)*s++) * 16777619u;
    return 64u + h % 4093u;
}
